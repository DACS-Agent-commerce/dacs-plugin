// Real Chrome trusted approval over actual MCP/portal/broker. Native fixture
// RPC normalizes SDK wire content. Commitment is simulated, payment stays held.
import test from 'node:test';
import assert from 'node:assert/strict';
import { canonicalize, finalityCommitmentAddress, sha256Hex } from '@kynesyslabs/dacs';
import { startSr2Harness, startSr2Seller } from './helpers/seller-sr2-agreement-harness.mjs';
import { tool, linkedUser, tokenFrom } from './helpers/flows.mjs';
import { memoryAnchorJournal } from './helpers/dacs-storage-anchor-wallet-fixture.mjs';
import { installLoopbackOnlyGuard, externalAttempts } from './helpers/embedded-wallet-flow-fixtures.mjs';
import { launchTestChrome, openRecordedPage, createCleanupStack, freshPassword, uiCreate, uiUnlock, UI, assertNoSecrets } from './helpers/embedded-wallet-fixtures.mjs';
installLoopbackOnlyGuard();

test('Chrome realistic public-projection consumer: built-in wallet approved CREATE -> seller HTTP -> fresh verified commitment -> durable restart, one CREATE and one commitment effect, payment held', { timeout: 150000 }, async (t) => {
  const cleanup = createCleanupStack(); t.after(() => cleanup.run());
  const memory = memoryAnchorJournal(), journal = { ...memory, entries: () => memory.snapshot() };
  const h = await startSr2Harness({ journal, sellerSr2Commitment: { commitmentSubstrate: 'fixture', publicProjection: true } });
  cleanup.add('public sr2 harness', 10000, () => h.close());
  assert.equal(h.sellerChainUrl, h.chain.url, 'realistic RPC, no idealized front');
  const launched = await launchTestChrome(cleanup);
  t.diagnostic(`browser-real Chrome ${launched.version}; ${launched.executablePath}`);
  const rec = await openRecordedPage(launched.browser, cleanup), { page } = rec;
  await page.route('**/*', (route) => new URL(route.request().url()).origin === h.origin ? route.continue() : route.abort());
  const user = await linkedUser(h);
  await page.goto((await tool(h, user, 'start_wallet_link')).linkUrl);
  await page.getByRole('button', { name: 'Use the experimental embedded wallet' }).click();
  const walletUi = page.locator('#embedded-wallet'), password = freshPassword();
  const address = await uiCreate(walletUi, password);
  await page.getByRole('button', { name: 'Connect wallet' }).click();
  await page.getByText(`Connected: ${address} (experimental embedded wallet)`, { exact: true }).waitFor();
  await page.getByRole('button', { name: /^Sign and link/ }).click();
  await page.getByRole('dialog').getByText('purpose: link-wallet', { exact: false }).waitFor();
  await page.getByRole('dialog').getByRole('button', { name: UI.approve }).click();
  await page.getByRole('heading', { name: /^Wallet linked/ }).waitFor();
  const seller = await startSr2Seller(h, { listingId: 'public-sr2-browser', durable: true });
  const prepared = await tool(h, user, 'prepare_purchase', { listingId: seller.listing.listingId, version: 1, seller: seller.wallet.claim, walletAddress: address, idempotencyKey: `public-sr2-browser-${Date.now()}`, protocol: 'dacs-sr2-wallet-agreement' });
  assert.equal(prepared.status, 'agreement_pending', JSON.stringify(prepared));
  await page.goto(prepared.approvalUrl);
  await page.getByRole('button', { name: 'Use the experimental embedded wallet' }).click();
  assert.equal(await uiUnlock(walletUi, password), address);
  await page.getByRole('button', { name: 'Connect wallet' }).click();
  await page.getByText(`Connected: ${address} (experimental embedded wallet)`, { exact: true }).waitFor();
  await page.locator('#dacs-sign-agreement').click();
  const dialog = page.getByRole('dialog');
  await dialog.waitFor(); await dialog.getByRole('button', { name: UI.approve }).click();
  await dialog.getByLabel('Exact content to approve').waitFor(); await dialog.getByRole('button', { name: UI.approve }).click();
  await dialog.getByText('purpose: offline-agreement-browser-session', { exact: false }).waitFor(); await dialog.getByRole('button', { name: UI.approve }).click();
  await dialog.getByLabel('Exact content to approve').waitFor();
  const shown = JSON.parse(await dialog.getByLabel('Exact content to approve').textContent());
  assert.equal(shown.kind, 'dacs-storage-anchor-create'); assert.equal(shown.artifactKind, 'Agreement');
  assert.equal(h.chain.wire.record.broadcastAttempts.length, 0);
  await dialog.getByRole('button', { name: UI.approve }).click();
  await page.locator('#flow').getByText(/seller verified your native SR-2 Agreement CREATE/).waitFor({ timeout: 30000 });
  const status = await tool(h, user, 'verify_deal', { operationId: prepared.operationId });
  assert.equal(status.protocol.stage, 'seller-committed', JSON.stringify(status.protocol.lastAttempt));
  assert.equal(status.status, 'agreement_pending'); assert.equal(status.protocol.limits.payment, 'held');
  assert.equal(status.protocol.commitment.signer, seller.wallet.claim);
  const operation = h.app.services.ops.get(h.app.services.accounts.walletOwner(address), prepared.operationId), p = operation.state.protocol;
  const tx = h.chain.wire.record.accepted[0];
  assert.equal(canonicalize(tx.content.data[1].data), shown.exactStorageBytes);
  assert.equal(JSON.stringify(p.agreement.signedProjection), JSON.stringify(tx));
  const executed = await fetch(h.chain.url, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ method: 'nodeCall', params: [{ message: 'getTxByHash', data: { hash: tx.hash } }] }) }).then((r) => r.json());
  assert.equal(typeof executed.response.content.nonce, 'string'); assert.notEqual(sha256Hex(JSON.stringify(executed.response.content)), tx.hash);
  await seller.restart();
  const resumed = await fetch(`${seller.origin}/dacs/v1/commitments`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ jobId: operation.terms.protocol.jobId }) }).then((r) => r.json());
  assert.equal(resumed.status, 'committed', JSON.stringify(resumed)); assert.equal(resumed.resumed, true);
  assert.equal(resumed.agreementAnchor.nativeAddress, p.agreement.anchorReceipt.nativeAddress);
  assert.equal((await tool(h, user, 'verify_deal', { operationId: prepared.operationId })).protocol.commitment.contentHash, status.protocol.commitment.contentHash);
  assert.deepEqual(seller.anchorWrites, [finalityCommitmentAddress(operation.terms.protocol.jobId)]);
  assert.equal(h.chain.wire.record.broadcastAttempts.length, 1); assert.equal(h.chain.wire.record.accepted.length, 1);
  assert.ok(seller.requests.includes('/dacs/v1/commitments')); assert.ok(!seller.requests.includes('/dacs/v1/payments'));
  assert.equal(await page.locator('#flow').getByRole('button', { name: /Approve.*purchase|Pay now|Approve exact terms/ }).count(), 0);
  const held = await fetch(`${h.origin}/portal/api/purchase/${prepared.operationId}/challenge`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ token: tokenFrom(prepared.approvalUrl), address }) }).then((r) => r.json());
  assert.equal(held.error, 'agreement_payment_held');
  assertNoSecrets(rec.requests, [password], 'browser HTTP requests'); assertNoSecrets(h.logs, [password], 'server logs');
  assert.ok(rec.requests.every((r) => new URL(r.url).origin === h.origin)); assert.deepEqual(rec.consoleErrors, []);
  t.diagnostic(JSON.stringify({ stage: status.protocol.stage, nativeAddress: p.agreement.anchorReceipt.nativeAddress, createHash: tx.hash, commitmentHash: status.protocol.commitment.contentHash, buyerBroadcasts: 1, commitmentWrites: 1, durableRestart: seller.restarts(), payment: 'held', rpc: 'realistic-normalizing', transport: 'legacy-loopback' }));
});

test('Chrome public projection connections stayed loopback', () => assert.deepEqual(externalAttempts, []));
